"""Generate the KiCad 10 low-voltage control carrier PCB.

Run inside the KiCad Flatpak: flatpak run --command=python3 org.kicad.KiCad generate_board.py
"""
from pathlib import Path
import pcbnew as p

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "control-board.kicad_pcb"
board = p.BOARD()

def pos(x, y):
    return p.VECTOR2I(p.FromMM(x), p.FromMM(y))

def fp(lib, name, ref, value, x, y, angle=0):
    path = ROOT / "footprints" / f"{lib}.pretty"
    item = p.FootprintLoad(str(path), name)
    if item is None:
        raise RuntimeError(f"Cannot load {lib}:{name}")
    board.Add(item)
    item.SetReference(ref)
    item.SetValue(value)
    item.SetPosition(pos(x, y))
    if angle:
        item.SetOrientationDegrees(angle)
    return item

def net(name):
    item = p.NETINFO_ITEM(board, name)
    board.Add(item)
    return item

N = {name: net(name) for name in [
    "+5V", "GND", "+3V3", "QR_TX", "QR_RX", "IR32", "HOME33", "OPEN34",
    "PWM25", "DIR26", "FLT27", "IR_COM", "OPTO_ANODE",
]}

def attach(item, mapping):
    seen = set()
    for pad in item.Pads():
        number = pad.GetNumber()
        if number in mapping:
            pad.SetNet(N[mapping[number]])
            seen.add(number)
    if seen != set(mapping):
        raise ValueError(f"{item.GetReference()}: missing pads {set(mapping)-seen}")

socket = "PinSocket_1x19_P2.54mm_Vertical"
term2 = "TerminalBlock_Phoenix_MKDS-1,5-2-5.08_1x02_P5.08mm_Horizontal"
term4 = "TerminalBlock_Phoenix_MKDS-1,5-4-5.08_1x04_P5.08mm_Horizontal"
res10 = "R_Axial_DIN0207_L6.3mm_D2.5mm_P7.62mm_Horizontal"
res05 = "R_Axial_DIN0411_L9.9mm_D3.6mm_P12.70mm_Horizontal"

parts = [
    ("J7", fp("Connector_PinSocket_2.54mm", socket, "J7", "ESP32 J2", 44, 18),
     {"1":"+3V3", "5":"OPEN34", "7":"IR32", "8":"HOME33", "9":"PWM25", "10":"DIR26", "11":"FLT27", "14":"GND", "19":"+5V"}),
    ("J8", fp("Connector_PinSocket_2.54mm", socket, "J8", "ESP32 J3", 69.4, 18),
     {"1":"GND", "7":"GND", "11":"QR_RX", "12":"QR_TX"}),
    ("J1", fp("TerminalBlock_Phoenix", term2, "J1", "5V BUCK", 8, 15),
     {"1":"+5V", "2":"GND"}),
    ("J2", fp("TerminalBlock_Phoenix", term4, "J2", "QR UART", 8, 35),
     {"1":"+3V3", "2":"GND", "3":"QR_TX", "4":"QR_RX"}),
    ("J3", fp("TerminalBlock_Phoenix", term4, "J3", "MOTOR DRIVER LOGIC", 88, 15),
     {"1":"GND", "2":"PWM25", "3":"DIR26", "4":"FLT27"}),
    ("J4", fp("TerminalBlock_Phoenix", term2, "J4", "IR RELAY COM NO", 8, 67),
     {"1":"IR_COM", "2":"GND"}),
    ("J5", fp("TerminalBlock_Phoenix", term2, "J5", "LIMIT HOME NC", 88, 55),
     {"1":"GND", "2":"HOME33"}),
    ("J6", fp("TerminalBlock_Phoenix", term2, "J6", "LIMIT OPEN NC", 88, 76),
     {"1":"GND", "2":"OPEN34"}),
    ("U5", fp("Package_DIP", "DIP-4_W7.62mm", "U5", "PC817", 30, 70),
     {"1":"OPTO_ANODE", "2":"IR_COM", "3":"GND", "4":"IR32"}),
    ("R1", fp("Resistor_THT", res05, "R1", "330R 0.5W", 26, 83),
     {"1":"+5V", "2":"OPTO_ANODE"}),
    ("R2", fp("Resistor_THT", res10, "R2", "10k IR", 30, 25),
     {"1":"+3V3", "2":"IR32"}),
    ("R3", fp("Resistor_THT", res10, "R3", "10k HOME", 30, 34),
     {"1":"+3V3", "2":"HOME33"}),
    ("R4", fp("Resistor_THT", res10, "R4", "10k OPEN", 30, 43),
     {"1":"+3V3", "2":"OPEN34"}),
    ("R5", fp("Resistor_THT", res10, "R5", "10k FLT", 30, 52),
     {"1":"+3V3", "2":"FLT27"}),
]
for _, item, mapping in parts:
    attach(item, mapping)
for ref, x, y in [("H1", 4, 4), ("H2", 111, 4), ("H3", 4, 91), ("H4", 111, 91)]:
    hole = fp("MountingHole", "MountingHole_3.2mm_M3", ref, "M3", x, y)
    hole.Reference().SetVisible(False)

def edge(x1, y1, x2, y2):
    line = p.PCB_SHAPE(board)
    line.SetShape(p.SHAPE_T_SEGMENT)
    line.SetStart(pos(x1, y1))
    line.SetEnd(pos(x2, y2))
    line.SetLayer(p.Edge_Cuts)
    line.SetWidth(p.FromMM(0.05))
    board.Add(line)

for a, b, c, d in [(0,0,115,0),(115,0,115,95),(115,95,0,95),(0,95,0,0)]:
    edge(a,b,c,d)

def label(s, x, y, size=1.0):
    item = p.PCB_TEXT(board)
    item.SetText(s)
    item.SetPosition(pos(x,y))
    item.SetLayer(p.F_SilkS)
    item.SetTextSize(pos(size,size))
    item.SetTextThickness(p.FromMM(0.15))
    board.Add(item)

label("TURNSTILE CONTROL REV A", 57, 5, 1.4)
label("ESP32 DEVKITC V4 / WROOM", 57, 11, 1.0)
label("ANTENNA / NO COPPER", 57, 14, 0.8)
label("5V  GND", 10.5, 23)
label("3V3 GND TX RX", 15.5, 43)
label("IR COM / NO", 10.5, 75)
label("GND PWM DIR FLT", 95.5, 23)
label("GND HOME", 90.5, 63)
label("GND OPEN", 90.5, 84)

# A complete two-layer route is generated by route_board.py after this file is saved.
p.SaveBoard(str(OUT), board)
print(f"Saved {OUT} with {len(parts)} electrical footprints and 4 mounting holes")
